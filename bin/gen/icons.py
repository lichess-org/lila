#!/usr/bin/env python3

import math
import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from os.path import relpath
from pathlib import Path


SAFE_NAME_RE = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")


@dataclass(frozen=True)
class Icon:
    key: str
    name: str
    path: str
    view_box: str


def valid_view_box(view_box: str) -> bool:
    try:
        values = [float(value) for value in view_box.split()]
    except ValueError:
        return False
    return (
        len(values) == 4 and all(math.isfinite(value) for value in values)
    )


def pascal_case(name: str) -> str:
    return "".join(part[0].upper() + part[1:] for part in name.split("-"))


def read_icon(file: Path) -> Icon:
    name = file.stem
    if not SAFE_NAME_RE.fullmatch(name):
        raise ValueError(f"Invalid icon filename {file.name!r}")

    try:
        root = ET.parse(file).getroot()
    except ET.ParseError as error:
        raise ValueError(f"Invalid SVG {name!r}: {error}") from error

    if root.tag != "{http://www.w3.org/2000/svg}svg":
        raise ValueError(f"{name!r} must have one root in the svg namespace")
    if set(root.attrib) != {"viewBox"}:
        raise ValueError(f"unsupported attributes in {name!r}")
    view_box = root.attrib["viewBox"]
    if not valid_view_box(view_box):
        raise ValueError(f"invalid viewBox in {name!r}")

    children = list(root)
    if len(children) != 1:
        raise ValueError(f"{name!r} must contain exactly one path")
    if set(children[0].attrib) != {"d"}:
        raise ValueError(f"unsupported path attributes in {name!r}")
    path = children[0].attrib["d"]

    return Icon(pascal_case(name), name, path, view_box)


preamble = "// This file is generated by bin/gen/icons.py from public/images/svg-icons. Do not edit it\n"


def typescript_source(icons: list[Icon]) -> str:
    entries = "\n".join(f"  {icon.key}: '{icon.name}'," for icon in icons)
    return f"""{preamble}
export const icons = {{\n{entries}\n}} as const;
export type Icons = typeof icons;
export type IconKey = keyof Icons;
export type Icon = Icons[IconKey];
export type IconName = Icon;\n"""


def scala_source(icons: list[Icon]) -> str:
    constants = "\n".join(f'  val {icon.key}: Icon = "{icon.name}"' for icon in icons)
    return f"""{preamble}
package lila.ui

opaque type Icon = String
object Icon:
  extension (icon: Icon) def name: String = icon
  given scalalib.Iso.StringIso[Icon] = scalalib.Iso.string(identity, _.name)
  given play.api.libs.json.Writes[Icon] =
    play.api.libs.json.Writes(icon => play.api.libs.json.JsString(icon.name))

{constants}\n"""


def scss_source(icons: list[Icon]) -> str:
    constants = "\n".join(f"$icon-{icon.key}: '{icon.name}';" for icon in icons)
    urls = "\n".join(f"  $icon-{icon.key}: url('../images/svg-icons/{icon.name}.svg')," for icon in icons)
    classes = "\n\n".join(
        f".icon-{icon.name} {{\n  ---icon-src: #{{icon-url($icon-{icon.key})}};\n}}"
        for icon in icons
    )
    return f"""{preamble}
@use 'sass:map';

{constants}
$icon-urls: (
{urls}
);

@function icon-url($icon) {{
  @return map.get($icon-urls, $icon);
}}

{classes}
"""


def write_changed(file: Path, source: str) -> None:
    if file.exists() and file.read_text() == source:
        return
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(source)


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    source_dir = root / "public/images/svg-icons"
    outputs = [
        root / "modules/ui/src/main/Icons.scala",
        root / "ui/lib/css/abstract/_icons.scss",
        root / "ui/lib/src/icons.ts",
    ]
    files = sorted(source_dir.glob("*.svg"))
    if not files:
        raise ValueError(f"No SVG icons found in {source_dir!s}")
    icons = [read_icon(file) for file in files]
    if len({icon.key for icon in icons}) != len(icons):
        raise ValueError("Icon filenames must have unique PascalCase keys")

    for output, source in zip(outputs, (scala_source(icons), scss_source(icons), typescript_source(icons))):
        write_changed(output, source)
    print(f"Wrote {len(icons)} icons from {relpath(source_dir)}/*.svg to:")
    for output in outputs:
        print(f"  {relpath(output)}")


if __name__ == "__main__":
    main()
