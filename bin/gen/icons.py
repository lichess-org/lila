#!/usr/bin/env python3

import math
import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from os.path import relpath
from pathlib import Path


SAFE_NAME_RE = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")


@dataclass(frozen=True)
class Icon:
    key: str
    name: str
    mirror_rtl: bool
    @property
    def url(self) -> str:
        return f"../images/svg-icons/{self.name}.svg"


def valid_view_box(view_box: str) -> bool:
    try:
        values = [float(value) for value in view_box.split()]
    except ValueError:
        return False
    return (
        len(values) == 4 and all(math.isfinite(value) for value in values)
    )


def pascal_case(name: str) -> str:
    return "".join(part[0].upper() + part[1:] for part in name.split("-"))


def read_icon(file: Path) -> Icon:
    name = file.stem
    if not SAFE_NAME_RE.fullmatch(name):
        raise ValueError(f"Invalid icon filename {file.name!r}")

    try:
        root = ET.parse(file).getroot()
    except ET.ParseError as error:
        raise ValueError(f"Invalid SVG {name!r}: {error}") from error

    if root.tag != "{http://www.w3.org/2000/svg}svg":
        raise ValueError(f"{name!r} must have one root in the svg namespace")
    supported_attributes = {"viewBox", "data-mirror-rtl"}
    if not set(root.attrib) <= supported_attributes or "viewBox" not in root.attrib:
        raise ValueError(f"unsupported attributes in {name!r}")
    mirror_rtl = root.attrib.get("data-mirror-rtl")
    if mirror_rtl not in (None, "true"):
        raise ValueError(f"invalid data-mirror-rtl in {name!r}")
    view_box = root.attrib["viewBox"]
    if not valid_view_box(view_box):
        raise ValueError(f"invalid viewBox in {name!r}")

    return Icon(pascal_case(name), name, mirror_rtl == "true")


preamble = "// This file is generated by bin/gen/icons.py from public/images/svg-icons. Do not edit it\n"


def typescript_source(icons: list[Icon]) -> str:
    entries = "\n".join(f"  {icon.key}: '{icon.name}'," for icon in icons)
    mirrored = "\n".join(f"  '{icon.key}'," for icon in icons if icon.mirror_rtl)
    return f"""{preamble}
export const icons = {{\n{entries}\n}} as const;
export type Icons = typeof icons;
export type Icon = keyof Icons;

export const rtlMirroredIcons: ReadonlySet<Icon> = new Set([\n{mirrored}\n]);\n"""


def scala_source(icons: list[Icon]) -> str:
    constants = "\n".join(f'  case {icon.key} extends Icon("{icon.name}")' for icon in icons)
    mirrored = ",\n".join(f'    {icon.key}' for icon in icons if icon.mirror_rtl)
    return f"""{preamble}
package lila.ui

enum Icon(val name: String):
{constants}
  def key: String = productPrefix

object Icon:
  given play.api.libs.json.Writes[Icon] =
    play.api.libs.json.Writes(icon => play.api.libs.json.JsString(icon.name))
  def unsafe(name: String): Icon = values.find(_.name == name).get
  val rtlMirrored: Set[Icon] = Set(\n{mirrored}\n  )\n"""


def scss_source(icons: list[Icon]) -> str:
    constants = "\n".join(f"$icon-{icon.key}: url('{icon.url}');" for icon in icons)
    return f"""{preamble}
@use 'sass:map';

{constants}

@function icon-url($icon) {{
  @return map.get($icon-urls, $icon);
}}
"""


def scss_classes_source(icons: list[Icon]) -> str:
        classes = "\n\n".join(
                f".icon-{icon.name} {{\n  ---icon-src: url('{icon.url}');\n}}"
                for icon in icons
        )
        return f"""{preamble}
{classes}
"""


def html_source(icons: list[Icon]) -> str:
        entries = "\n".join(
        f'        <figure><img src="../images/svg-icons/{icon.name}.svg" alt=""><figcaption>{icon.key}</figcaption></figure>'
                for icon in icons
        )
        return f"""<!-- This file is generated by bin/gen/icons.py from public/images/svg-icons. Do not edit it -->
<!doctype html>
<html lang="en">
    <head>
        <meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>Lichess icons</title>
        <style>
            body {{
                display: grid;
                grid-template-columns: repeat(auto-fill, minmax(140px, 1fr));
                gap: 1px;
                margin: 8px;
            }}
            figure {{
                display: flex;
                flex-direction: column;
                align-items: center;
                gap: 4px;
                margin: 0;
                padding: 8px;
                outline: 1px solid #555;
            }}
            img {{
                box-sizing: border-box;
                width: 82px;
                height: 82px;
                padding: 8px;
            }}
            figcaption {{
                font: 12px/1.2 monospace;
                overflow-wrap: anywhere;
                text-align: center;
            }}
        </style>
    </head>
    <body>
{entries}
    </body>
</html>
"""


def write_changed(file: Path, source: str) -> None:
    if file.exists() and file.read_text() == source:
        return
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(source)


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    source_dir = root / "public/images/svg-icons"
    outputs = [
        root / "modules/ui/src/main/Icons.scala",
        root / "ui/lib/css/abstract/_icons.scss",
        root / "ui/lib/css/theme/_icons.scss",
        root / "ui/lib/src/icons.ts",
        root / "public/oops/icons.html",
    ]
    files = sorted(source_dir.glob("*.svg"))
    if not files:
        raise ValueError(f"No SVG icons found in {source_dir!s}")
    icons = [read_icon(file) for file in files]
    if len({icon.key for icon in icons}) != len(icons):
        raise ValueError("Icon filenames must have unique PascalCase keys")

    sources = (
        scala_source(icons),
        scss_source(icons),
        scss_classes_source(icons),
        typescript_source(icons),
        html_source(icons),
    )
    for output, source in zip(outputs, sources):
        write_changed(output, source)
    print(f"Wrote {len(icons)} icons from {relpath(source_dir)}/*.svg to:")
    for output in outputs:
        print(f"  {relpath(output)}")


if __name__ == "__main__":
    main()
